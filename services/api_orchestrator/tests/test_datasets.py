class TestViews:
    def test_refresh_builds_a_browsable_tree_of_symlinks(
        self, client: TestClient, layout: DataLayout
    ) -> None:
        capture_id = _capture(client, layout, operator="alice", task="pick")
        dataset = client.post(
            "/api/v1/datasets",
            json={"name": "pick_v1", "operator": "alice", "task": "pick"},
        ).json()
        client.post(
            f"/api/v1/datasets/{dataset['dataset_id']}/members",
            json={"capture_id": capture_id},
        )

        result = client.post("/api/v1/views/refresh").json()
        assert result["links"] == 1

        link = layout.views / "alice" / "pick" / "pick_v1" / "001"
        assert link.is_symlink()
        # Relative, so the tree stays valid when the data directory is moved or
        # bind-mounted at a different path.
        assert not link.readlink().is_absolute()
        assert link.resolve() == layout.capture_dir(capture_id).resolve()

    def test_views_is_a_symlink_that_is_flipped_not_rewritten(
        self, client: TestClient, layout: DataLayout
    ) -> None:
        capture_id = _capture(client, layout)
        dataset = client.post("/api/v1/datasets", json={"name": "ds"}).json()
        client.post(
            f"/api/v1/datasets/{dataset['dataset_id']}/members",
            json={"capture_id": capture_id},
        )

        first = client.post("/api/v1/views/refresh").json()["generation"]
        assert layout.views.is_symlink()
        second = client.post("/api/v1/views/refresh").json()["generation"]

        assert first != second
        # There is never a moment at which views/ does not resolve: the new tree
        # is built beside the old one and the symlink is replaced atomically.
        assert layout.views.is_symlink()
        assert layout.views.readlink().name.endswith(second)

    def test_a_member_with_no_local_copy_is_reported_not_linked(
        self, client: TestClient, layout: DataLayout
    ) -> None:
        import shutil

        capture_id = _capture(client, layout)
        dataset = client.post("/api/v1/datasets", json={"name": "ds"}).json()
        client.post(
            f"/api/v1/datasets/{dataset['dataset_id']}/members",
            json={"capture_id": capture_id},
        )
        shutil.rmtree(layout.capture_dir(capture_id))

        result = client.post("/api/v1/views/refresh").json()
        # A dangling symlink reads to every downstream tool as a corrupt
        # dataset; an absent one plus a report is a fact somebody can act on.
        assert result["links"] == 0
        assert len(result["skipped"]) == 1
        assert capture_id in result["skipped"][0]

    def test_a_pre_v2_views_directory_is_replaced(
        self, client: TestClient, layout: DataLayout
    ) -> None:
        stale = layout.views
        stale.mkdir(parents=True, exist_ok=True)
        (stale / "leftover.txt").write_text("old", encoding="utf-8")

        client.post("/api/v1/views/refresh")
        # The tree is generated, so there is nothing in the old one worth
        # keeping — and leaving it would make every future flip fail.
        assert layout.views.is_symlink()



    def test_selection_recipe_replay_rescues_a_lost_dataset_head(
        self, client: TestClient, layout: DataLayout, instance_id: str
    ) -> None:
        recipe = {
            "recipe_id": "rescued-recipe",
            "recorded_at": "2026-08-01T00:00:00Z",
            "kind": "filtered_bulk",
            "join": "or",
            "conditions": [
                {"field": "condition", "operator": "equals", "value": "left"}
            ],
            "matched": 1,
            "attempted": 1,
            "succeeded": 1,
            "failed": 0,
            "catalog_truncated": False,
        }
        # A truncated ledger head can lose dataset_created while leaving a
        # later recipe event. That event carries enough labels to reconstruct
        # the Dataset and its provenance without inventing a new history.
        ledger_v2.append(
            layout.data_dir,
            "dataset_selection_recorded",
            instance_id=instance_id,
            payload={
                "dataset_id": "lost-head",
                "dataset_name": "rescued",
                "name": "rescued",
                "operator": "alice",
                "task": "pick",
                "recipe": recipe,
            },
        )

        service = client.app.state.dataset_service
        service.restore_from_ledger()
        row = client.app.state.capture_store.get_dataset("lost-head")
        assert row is not None
        assert row["name"] == "rescued"
        assert json.loads(row["selection_recipes"]) == [recipe]
        # Forced rebuilds replay the ledger on top of a live index; recipe
        # history remains immutable rather than duplicating its one run.
        service.restore_from_ledger()
        replayed = client.app.state.capture_store.get_dataset("lost-head")
        assert replayed is not None
        assert json.loads(replayed["selection_recipes"]) == [recipe]

